#!/usr/bin/env python3
"""Export publication-style LaTeX tables from unified_all_suites.json.

Reads:  results/full_benchmark/unified_all_suites.json (run recompute_all_unified.py first)
Writes: outputs/tables/tab_benchmark_*.tex

Usage:
    python scripts/eval/export_latex_tables.py
    python scripts/eval/export_latex_tables.py --results_dir results/full_benchmark --out_dir outputs/tables
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def esc(s: str) -> str:
    return s.replace("_", "\\_").replace("%", "\\%")


def fmt_float(x: float | None, nd: int = 2) -> str:
    if x is None:
        return "---"
    try:
        import math

        if isinstance(x, float) and math.isnan(x):
            return "---"
    except Exception:
        pass
    return f"{x:.{nd}f}"


def fmt_pct(x: float | None, nd: int = 1) -> str:
    if x is None:
        return "---"
    try:
        import math

        if isinstance(x, float) and math.isnan(x):
            return "---"
    except Exception:
        pass
    return f"{x * 100:.{nd}f}\\%"


def main() -> None:
    p = argparse.ArgumentParser(description="Export LaTeX benchmark tables")
    p.add_argument(
        "--results_dir",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "results" / "full_benchmark",
    )
    p.add_argument(
        "--out_dir",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "outputs" / "tables",
    )
    args = p.parse_args()

    unified_path = args.results_dir / "unified_all_suites.json"
    if not unified_path.is_file():
        raise SystemExit(
            f"Missing {unified_path}. Run:\n"
            "  bash scripts/run_with_env.sh python scripts/eval/recompute_all_unified.py "
            f"--results_dir {args.results_dir}"
        )

    with open(unified_path, encoding="utf-8") as f:
        rows: list[dict] = json.load(f)

    SUITE_ORDER = ["External", "Icl", "Rag", "Tool", "History"]
    SUITE_SHORT = {
        "External": "Ext.",
        "History": "Hist.",
        "Icl": "ICL",
        "Rag": "RAG",
        "Tool": "Tool",
    }
    MODEL_ORDER = [
        "Llama-1B",
        "Llama-3B",
        "Llama-8B",
        "Qwen-1.5B",
        "Qwen-3B",
        "Qwen-7B",
        "Gemma-1B",
        "Gemma-4B",
        "OLMo-13B",
        "OLMo-32B",
    ]

    # (suite, model) -> metrics
    by_sm: dict[tuple[str, str], dict] = {}
    for r in rows:
        suite = r.get("suite")
        model = r.get("model")
        if suite and model:
            by_sm[(suite, model)] = r

    args.out_dir.mkdir(parents=True, exist_ok=True)

    # --- Wide: DiscΔ (model × suite) ---
    lines = [
        "% Auto-generated by scripts/eval/export_latex_tables.py",
        "% Requires: \\usepackage{booktabs}",
        "\\begin{tabular}{l" + "r" * len(SUITE_ORDER) + "}",
        "\\toprule",
        "Model & "
        + " & ".join(esc(SUITE_SHORT[s]) for s in SUITE_ORDER)
        + " \\\\",
        "\\midrule",
    ]
    for model in MODEL_ORDER:
        cells = [esc(model)]
        for suite in SUITE_ORDER:
            rec = by_sm.get((suite, model), {})
            dd = rec.get("disc_delta")
            cells.append(fmt_float(dd))
        lines.append(" & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    out_wide = args.out_dir / "tab_benchmark_disc_delta_wide.tex"
    out_wide.write_text("\n".join(lines), encoding="utf-8")

    # --- Wide: Parse rate (model × suite) ---
    lines_p = [
        "% Auto-generated by scripts/eval/export_latex_tables.py",
        "\\begin{tabular}{l" + "r" * len(SUITE_ORDER) + "}",
        "\\toprule",
        "Model & "
        + " & ".join(esc(SUITE_SHORT[s]) for s in SUITE_ORDER)
        + " \\\\",
        "\\midrule",
    ]
    for model in MODEL_ORDER:
        cells = [esc(model)]
        for suite in SUITE_ORDER:
            rec = by_sm.get((suite, model), {})
            pr = rec.get("parse_rate")
            cells.append(fmt_pct(pr))
        lines_p.append(" & ".join(cells) + " \\\\")
    lines_p.extend(["\\bottomrule", "\\end{tabular}", ""])
    (args.out_dir / "tab_benchmark_parse_rate_wide.tex").write_text(
        "\n".join(lines_p), encoding="utf-8"
    )

    # --- Compact long-form (suite, model, Acc10_c, DiscΔ, Parse) with % formatting ---
    lines_l = [
        "% Auto-generated — long format; good for single-column appendix",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Suite & Model & Acc$_{10}^c$ & Disc$\\Delta$ & Parse \\\\",
        "\\midrule",
    ]
    for suite in SUITE_ORDER:
        for model in MODEL_ORDER:
            rec = by_sm.get((suite, model), {})
            if not rec:
                continue
            lines_l.append(
                f"{esc(SUITE_SHORT[suite])} & {esc(model)} & "
                f"{fmt_pct(rec.get('acc10_control'))} & "
                f"{fmt_float(rec.get('disc_delta'))} & "
                f"{fmt_pct(rec.get('parse_rate'))} \\\\"
            )
    lines_l.extend(["\\bottomrule", "\\end{tabular}", ""])
    (args.out_dir / "tab_benchmark_condensed_pct.tex").write_text(
        "\n".join(lines_l), encoding="utf-8"
    )

    print(f"Wrote {out_wide.relative_to(args.out_dir.parent.parent)}")
    print(f"Wrote {args.out_dir / 'tab_benchmark_parse_rate_wide.tex'}")
    print(f"Wrote {args.out_dir / 'tab_benchmark_condensed_pct.tex'}")


if __name__ == "__main__":
    main()
