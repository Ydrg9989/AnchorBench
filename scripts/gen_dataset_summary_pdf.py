#!/usr/bin/env python3
"""Generate a PDF summarizing the PoC dataset and experiment settings."""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

from fpdf import FPDF


ROOT = Path(__file__).resolve().parents[1]
DATASET = ROOT / "data/processed/icl_anchor_v0/dataset.jsonl"
SPECS = ROOT / "data/interim/icl_anchor_v0/template_specs.json"
DATA_CFG = ROOT / "configs/data_gen.yaml"
EVAL_CFG = ROOT / "configs/eval.yaml"
OUT_PDF = ROOT / "results/dataset_and_experiment_summary.pdf"


def _latin1_safe(text: str) -> str:
    """Replace non-latin1 characters for core-font PDF rendering."""
    replacements = {
        "\u2014": "--", "\u2013": "-", "\u2018": "'", "\u2019": "'",
        "\u201c": '"', "\u201d": '"', "\u2026": "...", "\u2192": "->",
        "\u2264": "<=", "\u2265": ">=", "\u2248": "~",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text.encode("latin-1", errors="replace").decode("latin-1")


class SummaryPDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.cell(0, 8, "LLM Anchoring - PoC Dataset & Experiment Summary", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(60, 60, 60)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}}", align="C")

    def section(self, title: str):
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(30, 30, 120)
        self.ln(3)
        self.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(30, 30, 120)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(2)
        self.set_text_color(0, 0, 0)

    def subsection(self, title: str):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(60, 60, 60)
        self.ln(2)
        self.cell(0, 6, title, new_x="LMARGIN", new_y="NEXT")
        self.ln(1)
        self.set_text_color(0, 0, 0)

    def body_text(self, text: str):
        self.set_font("Helvetica", "", 9)
        self.multi_cell(0, 4.5, _latin1_safe(text))
        self.ln(1)

    def kv(self, key: str, value: str):
        self.set_font("Helvetica", "B", 9)
        self.cell(55, 5, _latin1_safe(key) + ":")
        self.set_font("Helvetica", "", 9)
        self.cell(0, 5, _latin1_safe(str(value)), new_x="LMARGIN", new_y="NEXT")

    def table(self, headers: list[str], rows: list[list[str]],
              col_widths: list[float] | None = None):
        if col_widths is None:
            w = (self.w - 20) / len(headers)
            col_widths = [w] * len(headers)
        self.set_font("Helvetica", "B", 8)
        self.set_fill_color(230, 230, 245)
        for h, cw in zip(headers, col_widths):
            self.cell(cw, 5.5, _latin1_safe(h), border=1, fill=True, align="C")
        self.ln()
        self.set_font("Helvetica", "", 8)
        for i, row in enumerate(rows):
            fill = i % 2 == 1
            if fill:
                self.set_fill_color(245, 245, 250)
            for val, cw in zip(row, col_widths):
                self.cell(cw, 5, _latin1_safe(str(val)), border=1, fill=fill, align="C")
            self.ln()
        self.ln(2)


def load_dataset():
    records = [json.loads(l) for l in DATASET.read_text().strip().split("\n")]
    return records


def load_specs():
    return json.loads(SPECS.read_text())


def main():
    records = load_dataset()
    specs = load_specs()

    domains = Counter(r["domain"] for r in records)
    tids = Counter(r["template_id"] for r in records)
    conds = Counter(r["icl_condition"] for r in records)

    tv_by_tpl = defaultdict(list)
    for r in records:
        tv_by_tpl[r["template_id"]].append(r["truth_value"])

    anchor_by_cond = defaultdict(list)
    for r in records:
        if r["anchor_value"] is not None:
            anchor_by_cond[r["icl_condition"]].append(r["anchor_value"])

    import hashlib
    base_ids = set()
    for r in records:
        s = r["template_id"] + r["rendered_context"] + r["rendered_question"] + r["truth_formatted"]
        base_ids.add(hashlib.sha1(s.encode()).hexdigest())

    # --- Build PDF ---
    pdf = SummaryPDF()
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    # 1. Overview
    pdf.section("1  Dataset Overview")
    pdf.kv("Dataset version", "icl_anchor_v0")
    pdf.kv("Total prompt items", str(len(records)))
    pdf.kv("Unique base tasks", str(len(base_ids)))
    pdf.kv("Domains", f"{len(domains)} ({', '.join(sorted(domains))})")
    pdf.kv("Template types", str(len(tids)))
    pdf.kv("ICL conditions per base task", str(len(conds)))
    pdf.kv("Templates per spec", "3 (generated by GPT-4o-mini)")
    pdf.kv("Items per template", "10 (random variable instantiations)")
    pdf.kv("Format", "US currency, truth as plain 2-decimal digits")
    pdf.ln(2)

    pdf.body_text(
        "The dataset is constructed in two stages: (1) an LLM generates digit-free "
        "natural-language templates from structured specifications, and (2) a Python "
        "renderer instantiates each template with random numeric values, computes "
        "ground-truth answers via safe AST evaluation, and prepends ICL demonstrations "
        "with controlled anchor magnitudes. Each base task (unique context + question + "
        "truth) appears under all 5 ICL conditions, enabling paired within-task comparison."
    )

    # 2. Template Specifications
    pdf.section("2  Template Specifications")
    spec_rows = []
    for sp in specs:
        vr = sp["variable_ranges"]
        vars_str = ", ".join(f"{k}" for k in vr)
        expr = sp["truth_expression"]
        spec_rows.append([
            sp["id"], sp["domain"],
            vars_str, expr, sp["description"][:60] + "..."
        ])
    pdf.table(
        ["Template ID", "Domain", "Variables", "Truth Expr", "Description"],
        spec_rows,
        col_widths=[28, 18, 30, 28, 86],
    )

    # Variable ranges
    pdf.subsection("Variable Ranges")
    var_rows = []
    for sp in specs:
        for vname, vr in sp["variable_ranges"].items():
            vtype = vr.get("type", "float")
            dec = vr.get("decimals", "-")
            var_rows.append([sp["id"], vname, vtype, str(dec),
                             f"[{vr['min']}, {vr['max']}]"])
    pdf.table(
        ["Template", "Variable", "Type", "Decimals", "Range"],
        var_rows,
        col_widths=[30, 30, 18, 18, 40],
    )

    # 3. ICL Conditions
    pdf.section("3  ICL Conditions (Anchoring Manipulation)")
    pdf.body_text(
        "Each base task is presented under 5 in-context learning conditions. "
        "The anchored conditions prepend 2-shot demonstrations whose answer values "
        "fall in a controlled numeric range, serving as anchors. The no_demo baseline "
        "omits demonstrations entirely, and placeholder_demo uses symbolic tokens "
        "(<AMOUNT>) instead of digits to control for structural priming."
    )
    cond_rows = [
        ["no_demo", str(conds["no_demo"]), "-", "No ICL examples; bare question"],
        ["low_anchor_demo", str(conds["low_anchor_demo"]),
         f"[{min(anchor_by_cond['low_anchor_demo']):.0f}, "
         f"{max(anchor_by_cond['low_anchor_demo']):.0f}]",
         "2-shot demos with small anchor values"],
        ["high_anchor_demo", str(conds["high_anchor_demo"]),
         f"[{min(anchor_by_cond['high_anchor_demo']):.0f}, "
         f"{max(anchor_by_cond['high_anchor_demo']):.0f}]",
         "2-shot demos with large anchor values"],
        ["outlier_anchor_demo", str(conds["outlier_anchor_demo"]),
         f"[{min(anchor_by_cond['outlier_anchor_demo'])/1e6:.0f}M, "
         f"{max(anchor_by_cond['outlier_anchor_demo'])/1e6:.0f}M]",
         "2-shot demos with extreme anchor values"],
        ["placeholder_demo", str(conds["placeholder_demo"]),
         "-", "2-shot demos with <AMOUNT> tokens (digit-free)"],
    ]
    pdf.table(
        ["Condition", "N Items", "Anchor Range", "Description"],
        cond_rows,
        col_widths=[32, 16, 38, 104],
    )

    # 4. Truth Value Distribution
    pdf.section("4  Ground-Truth Value Distribution")
    tv_rows = []
    for tpl in sorted(tv_by_tpl):
        vals = sorted(set(tv_by_tpl[tpl]))
        tv_rows.append([
            tpl, str(len(vals)),
            f"{min(vals):.2f}", f"{max(vals):.2f}",
            f"{sum(vals)/len(vals):.2f}",
        ])
    pdf.table(
        ["Template", "Unique Values", "Min", "Max", "Mean"],
        tv_rows,
        col_widths=[35, 25, 30, 30, 30],
    )

    # 5. Experiment Settings
    pdf.section("5  Experiment Settings")
    pdf.subsection("5.1  Model Matrix")
    pdf.table(
        ["Model", "Params", "Preset", "Seeds", "Samples/item", "Runs"],
        [
            ["Llama-3.2-1B-Instruct", "1.2B", "sampling", "0, 1, 2", "20", "3"],
            ["Llama-3.2-3B-Instruct", "3.2B", "greedy", "0", "1", "1"],
            ["Llama-3.2-3B-Instruct", "3.2B", "sampling", "0, 1, 2", "20", "3"],
            ["Llama-3.1-8B-Instruct", "8.0B", "greedy", "0", "1", "1"],
            ["Llama-3.1-8B-Instruct", "8.0B", "sampling", "0, 1, 2", "20", "3"],
            ["Total", "", "", "", "", "11"],
        ],
        col_widths=[40, 14, 20, 22, 26, 12],
    )

    pdf.subsection("5.2  Decoding Configuration")
    pdf.table(
        ["Preset", "Temperature", "top_p", "Samples per item", "Purpose"],
        [
            ["greedy", "0.0", "-", "1", "Deterministic baseline (IAS ~ 0)"],
            ["sampling", "0.7", "0.9", "20", "Distributional anchoring signal"],
        ],
        col_widths=[22, 22, 16, 28, 60],
    )

    pdf.subsection("5.3  Generation Parameters")
    pdf.kv("max_new_tokens", "128")
    pdf.kv("batch_size", "128")
    pdf.kv("dtype", "auto (bfloat16 on supported HW)")
    pdf.kv("use_chat_template", "True")
    pdf.kv("anchor_collision_tol", "0.01 (1% relative)")

    # 6. Evaluation Methodology
    pdf.section("6  Evaluation Methodology")
    pdf.subsection("6.1  Parsing")
    pdf.body_text(
        "Outputs are parsed with a hierarchical deterministic parser. "
        "Level 0: clean number match. Level 1: <value> tag extraction. "
        "Level 2: keyword-line extraction (answer/total/final). "
        "Level 3: last-number fallback after currency normalization. "
        "The parser operates on completion text only -- never sees the prompt -- "
        "preventing anchor leakage through parsing."
    )

    pdf.subsection("6.2  Anchoring Metrics")
    pdf.body_text(
        "IAS (Induced Anchoring Shift): For each base task i, "
        "IAS_i = median(pred | high_anchor) - median(pred | low_anchor). "
        "Aggregated as mean and median across base tasks, "
        "with bootstrap 95% CI (2000 resamples over base_ids).\n\n"
        "OutlierShift: median(pred | outlier_anchor) - median(pred | low_anchor), "
        "computed analogously.\n\n"
        "Validity checks: anchor_collision_rate (parsed == anchor), "
        "mismatch_suspect_rate (from audit flags), and base coverage "
        "(both low + high conditions present)."
    )

    pdf.subsection("6.3  Robustness Checks")
    pdf.body_text(
        "(A) IAS with per-base mean instead of median. "
        "(B) IAS after excluding mismatch_suspect samples. "
        "(C) IAS for sampling-only runs (vs greedy baseline). "
        "Results are stable if conclusions are invariant across these variants."
    )

    # 7. Dataset Counts
    pdf.section("7  Summary Statistics")
    n_sampling = 90 * 20 * 9  # 90 items * 20 samples * 9 sampling runs
    n_greedy = 90 * 1 * 2     # 90 items * 1 sample * 2 greedy runs
    pdf.table(
        ["Statistic", "Value"],
        [
            ["Dataset items (prompts)", str(len(records))],
            ["Unique base tasks", str(len(base_ids))],
            ["ICL conditions", str(len(conds))],
            ["Domains", str(len(domains))],
            ["Template types", str(len(tids))],
            ["Models evaluated", "3"],
            ["Total experiment runs", "11"],
            ["Generations (sampling, expected)", f"{n_sampling:,}"],
            ["Generations (greedy, expected)", f"{n_greedy:,}"],
            ["Total generations (expected)", f"{n_sampling + n_greedy:,}"],
        ],
        col_widths=[70, 50],
    )

    # 8. Prompt Examples
    pdf.add_page()
    pdf.section("8  Prompt Examples (invoice_total)")

    cond_labels = {
        "no_demo": "No Demonstration",
        "low_anchor_demo": "Low Anchor (range: 1-50)",
        "high_anchor_demo": "High Anchor (range: 5k-50k)",
        "outlier_anchor_demo": "Outlier Anchor (range: 10M-1B)",
        "placeholder_demo": "Placeholder (digit-free)",
    }
    for cond in ["no_demo", "low_anchor_demo", "high_anchor_demo",
                 "outlier_anchor_demo", "placeholder_demo"]:
        for r in records:
            if r["template_id"] == "invoice_total" and r["icl_condition"] == cond:
                pdf.subsection(cond_labels[cond])
                prompt = r["final_prompt"]
                if len(prompt) > 500:
                    prompt = prompt[:480] + "\n[... truncated]"
                pdf.set_font("Courier", "", 7)
                pdf.multi_cell(0, 3.5, _latin1_safe(prompt))
                pdf.set_font("Helvetica", "I", 8)
                truth = r["truth_value"]
                anchor = r.get("anchor_value")
                anchor_str = f"{anchor}" if anchor else "N/A"
                pdf.cell(0, 4, f"Truth: {truth}   |   Anchor: {anchor_str}",
                         new_x="LMARGIN", new_y="NEXT")
                pdf.ln(2)
                break

    OUT_PDF.parent.mkdir(parents=True, exist_ok=True)
    pdf.output(str(OUT_PDF))
    print(f"PDF saved to {OUT_PDF}")


if __name__ == "__main__":
    main()
