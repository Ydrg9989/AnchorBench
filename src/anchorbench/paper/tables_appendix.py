def build_uai_summary(
    unified: list[dict],
    icl_dist_metrics: list[dict] | None = None,
) -> str:
    rows: list[tuple[str, float, float, float, str]] = []
    for suite in ("External", "History", "Icl", "Rag", "Tool"):
        cells = [r for r in unified if r.get("suite") == suite]
        irrs = [r["uai_irr"] for r in cells if r.get("uai_irr") is not None]
        pls = [r["uai_plaus"] for r in cells if r.get("uai_plaus") is not None]
        discs = [r["disc_delta"] for r in cells
                 if r.get("disc_delta") is not None]
        if not discs:
            continue
        n_pos = sum(1 for d in discs if d > 0)
        suite_label = SUITE_LATEX[suite]
        if suite == "Icl":
            suite_label = SUITE_LATEX[suite] + " (metadata)"
        rows.append((
            suite_label,
            float(np.mean(irrs)),
            float(np.mean(pls)),
            float(np.mean(discs)),
            f"{n_pos}/{len(discs)}",
        ))
        if suite == "Icl" and icl_dist_metrics:
            irrs_d = [m["uai_irr"] for m in icl_dist_metrics if m.get("uai_irr") is not None]
            pls_d = [m["uai_plaus"] for m in icl_dist_metrics if m.get("uai_plaus") is not None]
            discs_d = [m["disc_delta"] for m in icl_dist_metrics if m.get("disc_delta") is not None]
            if discs_d:
                n_pos_d = sum(1 for d in discs_d if d > 0)
                rows.append((
                    SUITE_LATEX["Icl"] + " (ICL-dist)",
                    float(np.mean(irrs_d)),
                    float(np.mean(pls_d)),
                    float(np.mean(discs_d)),
                    f"{n_pos_d}/{len(discs_d)}",
                ))

    excl_rows = [r for r in rows if "ICL-dist" not in r[0]]
    irrs_all = [r[1] for r in excl_rows]
    pls_all = [r[2] for r in excl_rows]
    discs_all = [r[3] for r in excl_rows]
    pos_total = sum(int(r[4].split("/")[0]) for r in excl_rows)
    n_total = sum(int(r[4].split("/")[1]) for r in excl_rows)

    lines: list[str] = []
    lines.append("% Auto-generated by anchorbench.paper.tables_appendix")
    lines.append("\\begin{table}[ht]")
    lines.append("  \\centering")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{@{}lrrrl@{}}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Suite}")
    lines.append("    & \\textbf{UAI\\textsubscript{irr}}")
    lines.append("    & \\textbf{UAI\\textsubscript{pls}}")
    lines.append("    & \\textbf{Disc$_{\\Delta}$}")
    lines.append("    & \\textbf{$\\frac{+}{n}$} \\\\")
    lines.append("    \\midrule")
    for label, irr, pls, disc, frac in rows:
        lines.append(f"    {label:<28} & {irr:5.2f} & {pls:5.2f} & {disc:5.2f} & {frac} \\\\")
    lines.append("    \\midrule")
    lines.append(
        f"    \\textit{{All (excl.\\ ICL-dist)}} & {np.mean(irrs_all):.2f}  "
        f"& {np.mean(pls_all):.2f} & {np.mean(discs_all):.2f} & {pos_total}/{n_total} \\\\"
    )
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("  \\caption{Mean anchoring influence by relevance and suite.")
    lines.append("    $+/n$: cells with Disc$_{\\Delta} > 0$.")
    lines.append("    ICL-dist uses distribution-matching demonstrations")
    lines.append("    (open-weight models only).}")
    lines.append("  \\label{tab:uai_summary}")
    lines.append("\\end{table}")
    return "\n".join(lines)


