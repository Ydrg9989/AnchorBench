def build_boundary(records_dirs: list[Path]) -> str:
    """Compute UAI_pls at delta in {15, 25, 40} on External + RAG, with and
    without items where the anchor is clipped to {0, 100}.
    """
    suites = ["external", "rag"]
    all_uai: dict[int, list[float]] = {15: [], 25: [], 40: []}
    excl_uai: dict[int, list[float]] = {15: [], 25: [], 40: []}
    for base in records_dirs:
        for suite in suites:
            suite_dir = base / suite
            if not suite_dir.is_dir():
                continue
            for model_dir in sorted(suite_dir.iterdir()):
                if not model_dir.is_dir():
                    continue
                rpath = model_dir / "results.jsonl"
                if not rpath.exists():
                    continue
                recs = load_records(str(rpath))
                items = group_by_item(recs)
                for iid, by_cond in items.items():
                    ctrl = by_cond.get("control")
                    if ctrl is None:
                        continue
                    y_c = ctrl.get("answer_int")
                    if y_c is None:
                        continue
                    for cond in ("plausible_low", "plausible_high"):
                        rec = by_cond.get(cond)
                        if rec is None:
                            continue
                        y_a = rec.get("answer_int")
                        a = rec.get("anchor_value")
                        if y_a is None or a is None:
                            continue
                        denom = a - y_c
                        if abs(denom) < 3.0:
                            continue
                        uai = (y_a - y_c) / denom
                        offset = None
                        anchors = rec.get("anchors")
                        if isinstance(anchors, dict):
                            offset = anchors.get("offset")
                        if offset is None:
                            offset = rec.get("anchor_offset")
                        if offset is None:
                            import re
                            m = re.search(r"-off(\d+)-", iid or "")
                            if m:
                                offset = int(m.group(1))
                        if offset is None or int(offset) not in (15, 25, 40):
                            continue
                        offset = int(offset)
                        all_uai[offset].append(uai)
                        if a not in (0, 100):
                            excl_uai[offset].append(uai)

    lines: list[str] = []
    lines.append("% Auto-generated by anchorbench.paper.tables_appendix")
    lines.append("\\begin{center}")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{@{}lccc@{}}")
    lines.append("    \\toprule")
    lines.append("    & $\\delta{=}15$ & $\\delta{=}25$ & $\\delta{=}40$ \\\\")
    lines.append("    \\midrule")
    means_all = [float(np.mean(all_uai[d])) if all_uai[d] else float("nan") for d in (15, 25, 40)]
    means_excl = [float(np.mean(excl_uai[d])) if excl_uai[d] else float("nan") for d in (15, 25, 40)]
    lines.append(f"    All items           & {means_all[0]:.2f} & {means_all[1]:.2f} & {means_all[2]:.2f} \\\\")
    lines.append(f"    Excl.\\ boundary     & {means_excl[0]:.2f} & {means_excl[1]:.2f} & {means_excl[2]:.2f} \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("\\end{center}")
    n_all_40 = len(all_uai[40])
    n_excl_40 = len(excl_uai[40])
    n_clipped = n_all_40 - n_excl_40
    lines.append(f"% Boundary clipping affects {n_clipped}/{n_all_40} "
                 f"({100*n_clipped/max(n_all_40,1):.1f}%) items at delta=40.")
    return "\n".join(lines)


