def compute_difficulty_table(unified: list[dict]) -> dict[str, dict[str, dict[str, float]]]:
    """Aggregate by_difficulty across models per suite."""
    out: dict[str, dict[str, dict[str, list[float]]]] = {}
    for r in unified:
        suite = r.get("suite")
        bd = r.get("by_difficulty", {})
        for diff, m in bd.items():
            bucket = out.setdefault(suite, {}).setdefault(
                diff, {"acc": [], "mae": [], "uai_irr": [],
                       "uai_plaus": [], "disc": []}
            )
            if m.get("acc10_control") is not None:
                bucket["acc"].append(m["acc10_control"])
            if m.get("mae_control") is not None:
                bucket["mae"].append(m["mae_control"])
            if m.get("uai_irr") is not None:
                bucket["uai_irr"].append(m["uai_irr"])
            if m.get("uai_plaus") is not None:
                bucket["uai_plaus"].append(m["uai_plaus"])
            if m.get("disc_delta") is not None:
                bucket["disc"].append(m["disc_delta"])
    summary: dict[str, dict[str, dict[str, float]]] = {}
    for suite, by_diff in out.items():
        summary[suite] = {}
        for diff, vals in by_diff.items():
            summary[suite][diff] = {k: (float(np.mean(v)) if v else float("nan"))
                                    for k, v in vals.items()}
    return summary


