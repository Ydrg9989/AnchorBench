def compute_unified_for_dir(records_dir: Path, suite: str | None = None) -> list[dict]:
    """Compute unified metrics for every results.jsonl under records_dir.

    Layout 1: ``records_dir/<suite>/<model_slug>/results.jsonl``
    Layout 2: ``records_dir/<model_slug>/results.jsonl`` (single suite)
    """
    out: list[dict] = []
    if any((p / "results.jsonl").exists() for p in records_dir.glob("*/")
           if p.is_dir()):
        for short, slug, path in discover_jsonl(records_dir.parent,
                                                records_dir.name):
            recs = load_records(str(path))
            if not recs:
                continue
            conds = {r.get("condition") for r in recs}
            bc = "control_twostage" if "control_twostage" in conds and "control" not in conds else "control"
            m = compute_unified_metrics(recs, baseline_condition=bc)
            m["model"] = short
            m["model_slug"] = slug
            m["suite"] = suite or records_dir.name.capitalize()
            out.append(m)
    return out


