def collect_pooled_uai(records_root: Path, baseline: str = "control",
                       suites: list[str] | None = None) -> dict[str, list[float]]:
    """Pool per-item UAI across all (model, suite) result files."""
    suites = suites or ["external", "history", "icl", "rag", "tool"]
    pooled: dict[str, list[float]] = {"irr": [], "plaus": []}
    for suite in suites:
        suite_dir = records_root / suite
        if not suite_dir.is_dir():
            continue
        for model_dir in sorted(suite_dir.iterdir()):
            if not model_dir.is_dir():
                continue
            rpath = model_dir / "results.jsonl"
            if not rpath.exists():
                continue
            recs = load_records(str(rpath))
            conds = {r.get("condition") for r in recs}
            bc = "control_twostage" if "control_twostage" in conds and "control" not in conds else "control"
            items = group_by_item(recs)
            for _iid, by_cond in items.items():
                ctrl = by_cond.get(bc)
                if ctrl is None:
                    continue
                y_ctrl = ctrl.get("answer_int")
                if y_ctrl is None:
                    continue
                for cond in ("irrelevant_low", "irrelevant_high",
                             "plausible_low", "plausible_high"):
                    rec = by_cond.get(cond)
                    if rec is None:
                        continue
                    y_a = rec.get("answer_int")
                    a = rec.get("anchor_value")
                    if y_a is None or a is None:
                        continue
                    denom = a - y_ctrl
                    if abs(denom) < 3.0:
                        continue
                    uai = (y_a - y_ctrl) / denom
                    if "irrelevant" in cond:
                        pooled["irr"].append(uai)
                    else:
                        pooled["plaus"].append(uai)
    return pooled


def build_uai_distribution(records_dirs: list[Path]) -> str:
    pooled: dict[str, list[float]] = {"irr": [], "plaus": []}
    for d in records_dirs:
        contribution = collect_pooled_uai(d)
        pooled["irr"].extend(contribution["irr"])
        pooled["plaus"].extend(contribution["plaus"])

    def stats(vals: list[float]) -> dict[str, float]:
        a = np.asarray(vals, dtype=float)
        return {
            "n": len(a),
            "in01": float(np.mean((a >= 0) & (a <= 1))),
            "over": float(np.mean(a > 1)),
            "rev": float(np.mean(a < 0)),
            "mean": float(a.mean()),
            "median": float(np.median(a)),
            "cap_mean": float(np.clip(a, 0, 1).mean()),
            "p5": float(np.percentile(a, 5)),
            "p25": float(np.percentile(a, 25)),
            "p75": float(np.percentile(a, 75)),
            "p95": float(np.percentile(a, 95)),
        }

    irr = stats(pooled["irr"])
    pls = stats(pooled["plaus"])

    lines: list[str] = []
    lines.append("% Auto-generated by anchorbench.paper.tables_appendix")
    lines.append("\\begin{table}[ht]")
    lines.append("  \\centering")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{@{}lrr@{}}")
    lines.append("    \\toprule")
    lines.append("    & \\textbf{UAI\\textsubscript{irr}} & \\textbf{UAI\\textsubscript{pls}} \\\\")
    lines.append("    \\midrule")
    lines.append(f"    In $[0,1]$       & {irr['in01']*100:.1f}\\% & {pls['in01']*100:.1f}\\% \\\\")
    lines.append(f"    Overshoot ($>1$)  & {irr['over']*100:.1f}\\%  & {pls['over']*100:.1f}\\%  \\\\")
    lines.append(f"    Reverse ($<0$)    & {irr['rev']*100:.1f}\\% & {pls['rev']*100:.1f}\\% \\\\")
    lines.append("    \\midrule")
    lines.append(f"    Mean              & {irr['mean']:.2f}   & {pls['mean']:.2f}   \\\\")
    lines.append(f"    Median            & {irr['median']:.2f}   & {pls['median']:.2f}   \\\\")
    lines.append(f"    Capped $[0,1]$ mean & {irr['cap_mean']:.2f} & {pls['cap_mean']:.2f}   \\\\")
    lines.append("    \\midrule")
    lines.append(f"    5th pctl          & {fmt_num(irr['p5'], 2)} & {fmt_num(pls['p5'], 2)} \\\\")
    lines.append(f"    25th pctl         & {irr['p25']:.2f}    & {pls['p25']:.2f}   \\\\")
    lines.append(f"    75th pctl         & {irr['p75']:.2f}    & {pls['p75']:.2f}   \\\\")
    lines.append(f"    95th pctl         & {irr['p95']:.2f}    & {pls['p95']:.2f}   \\\\")
    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("  \\caption{Distribution of per-item UAI values across all")
    lines.append(f"    models and suites ($n_{{\\text{{irr}}}}={irr['n']}$, "
                 f"$n_{{\\text{{pls}}}}={pls['n']}$).}}")
    lines.append("  \\label{tab:uai_distribution}")
    lines.append("\\end{table}")
    return "\n".join(lines)


