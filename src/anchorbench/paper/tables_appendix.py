def build_per_suite_table(unified: list[dict], suite: str, label: str,
                          caption: str) -> str:
    by_model = collect_per_suite(unified, suite)
    lines: list[str] = []
    lines.append(f"% Auto-generated by anchorbench.paper.tables_appendix "
                 f"-- {suite} per-suite results")
    lines.append("\\begin{table}[ht]")
    lines.append("  \\centering")
    lines.append("  \\small")
    lines.append("  \\tablestartstriped{3}")
    lines.append("  \\begin{tabular}{@{}lrrrrrrrr@{}}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Model}")
    lines.append("    & \\textbf{MAE\\textsubscript{c}}$\\,\\downarrow$")
    lines.append("    & \\textbf{Acc\\textsubscript{10} (\\%)}$\\,\\uparrow$")
    lines.append("    & \\textbf{UAI\\textsubscript{irr}}")
    lines.append("    & \\textbf{UAI\\textsubscript{pls}}")
    lines.append("    & \\textbf{TAR\\textsubscript{irr}}")
    lines.append("    & \\textbf{TAR\\textsubscript{pls}}")
    lines.append("    & \\textbf{Disc$_{\\Delta}$}")
    lines.append("    & \\textbf{Parse} \\\\")
    lines.append("    \\midrule")

    family_breaks = {"Llama-1B", "Gemma-1B", "OLMo-13B", "GPT-5.4-mini"}
    for model in ALL_MODELS_ORDER:
        if model in family_breaks:
            lines.append("    \\midrule")
        r = by_model.get(model)
        latex_name = short_to_latex(model)
        if r is None or r.get("parse_rate", 0) < 0.05:
            parse = r.get("parse_rate") if r else None
            parse_s = f"{parse:.2f}" if parse is not None else "---"
            lines.append(
                f"    {latex_name:<16} & ---   & ---  & ---   & ---  & ---  "
                f"& ---  & ---  & {parse_s} \\\\"
            )
            continue
        mae = fmt_num(r.get("mae_control"), 2)
        acc = fmt_pct1(r.get("acc10_control"))
        ui = fmt_num(r.get("uai_irr"), 2)
        up = fmt_num(r.get("uai_plaus"), 2)
        ti = fmt_num(r.get("tar_irr"), 2)
        tp = fmt_num(r.get("tar_plaus"), 2)
        dd = fmt_num(r.get("disc_delta"), 2)
        pr = (f"{r.get('parse_rate'):.2f}"
              if r.get("parse_rate") is not None else "---")
        lines.append(
            f"    {latex_name:<16} & {mae} & {acc} & {ui}  & {up} & {ti} & {tp} & {dd} & {pr} \\\\"
        )

    lines.append("    \\bottomrule")
    lines.append("  \\end{tabular}")
    lines.append("  \\tablestopstriped")
    lines.append(f"  \\caption{{{caption}}}")
    lines.append(f"  \\label{{{label}}}")
    lines.append("\\end{table}")
    return "\n".join(lines)


