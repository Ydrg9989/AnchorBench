"""Appendix LaTeX tables (COLM 2026).

Emits the following from existing ``unified_all_suites.json`` files
plus a small number of per-record JSONL passes for distribution and
boundary analyses:

* ``tab_app_external.tex``, ``tab_app_history.tex``, ``tab_app_icl.tex``,
  ``tab_app_rag.tex``, ``tab_app_tool.tex`` — Tables 4-8: full per-suite
  metrics for all 14 models.
* ``tab_uai_summary.tex`` — Table 9: cross-suite UAI summary + ICL-dist row.
* ``tab_stats_inference.tex`` — Table 10: contrasts with bootstrap CIs.
* ``tab_uai_distribution.tex`` — Table 11: pooled per-item UAI distribution.
* ``tab_anchored_mae.tex`` — Table 12: Delta-MAE by relevance and suite.
* ``tab_history_matched.tex`` — Table 13: matched-control History analysis.
* ``tab_icl_dist.tex`` — Table 14: ICL-metadata vs ICL-dist comparison.
* ``tab_tool_plaintext.tex`` — Table 15: structured vs plaintext Tool format.
* ``tab_difficulty.tex`` — Table 16: easy vs hard items by suite.
* ``tab_boundary.tex`` — boundary-clipping subtable.
* ``tab_model_details.tex`` — model panel description from anchorbench.eval.constants.

Outputs are written to ``outputs/tables/`` by default.

Usage:
    python anchorbench.paper.tables_appendix
"""

