def compute_delta_mae_by_suite(records_dirs: list[Path]) -> dict[str, dict[str, float]]:
    """Mean Delta-MAE by suite and relevance, averaged across models."""
    out: dict[str, dict[str, list[float]]] = {}
    for base in records_dirs:
        for suite in ("external", "history", "icl", "rag", "tool"):
            suite_dir = base / suite
            if not suite_dir.is_dir():
                continue
            for model_dir in sorted(suite_dir.iterdir()):
                if not model_dir.is_dir():
                    continue
                rpath = model_dir / "results.jsonl"
                if not rpath.exists():
                    continue
                recs = load_records(str(rpath))
                if not recs:
                    continue
                conds = {r.get("condition") for r in recs}
                bc = "control_twostage" if "control_twostage" in conds and "control" not in conds else "control"
                items = group_by_item(recs)
                mae_ctrl: list[float] = []
                mae_irr: list[float] = []
                mae_pls: list[float] = []
                for _iid, by_cond in items.items():
                    ctrl = by_cond.get(bc)
                    if ctrl is None:
                        continue
                    y_star = ctrl.get("y_star_evidence")
                    y_c = ctrl.get("answer_int")
                    if y_star is None or y_c is None:
                        continue
                    mae_ctrl.append(abs(y_c - y_star))
                    for cond in ("irrelevant_low", "irrelevant_high"):
                        rec = by_cond.get(cond)
                        if rec is None:
                            continue
                        y_a = rec.get("answer_int")
                        if y_a is None:
                            continue
                        mae_irr.append(abs(y_a - y_star))
                    for cond in ("plausible_low", "plausible_high"):
                        rec = by_cond.get(cond)
                        if rec is None:
                            continue
                        y_a = rec.get("answer_int")
                        if y_a is None:
                            continue
                        mae_pls.append(abs(y_a - y_star))
                if not mae_ctrl:
                    continue
                m_ctrl = float(np.mean(mae_ctrl))
                d_irr = float(np.mean(mae_irr) - m_ctrl) if mae_irr else None
                d_pls = float(np.mean(mae_pls) - m_ctrl) if mae_pls else None
                bucket = out.setdefault(suite, {"irr": [], "pls": []})
                if d_irr is not None:
                    bucket["irr"].append(d_irr)
                if d_pls is not None:
                    bucket["pls"].append(d_pls)
    summary: dict[str, dict[str, float]] = {}
    for suite, b in out.items():
        summary[suite] = {
            "irr": float(np.mean(b["irr"])) if b["irr"] else float("nan"),
            "pls": float(np.mean(b["pls"])) if b["pls"] else float("nan"),
        }
    return summary


def build_anchored_mae(delta: dict[str, dict[str, float]]) -> str:
    suite_to_key = {
        "External": "external", "History": "history", "Icl": "icl",
        "Rag": "rag", "Tool": "tool",
    }
    lines: list[str] = []
    lines.append("% Auto-generated by anchorbench.paper.tables_appendix")
    lines.append("\\begin{table}[ht]")
    lines.append("  \\centering")
    lines.append("  \\small")
    lines.append("  \\begin{tabular}{@{}lrr@{}}")
    lines.append("    \\toprule")
    lines.append("    \\textbf{Suite}")
    lines.append("    & \\textbf{$\\Delta$MAE\\textsubscript{irr}}")
    lines.append("    & \\textbf{$\\Delta$MAE\\textsubscript{pls}} \\\\")
    lines.append("    \\midrule")
